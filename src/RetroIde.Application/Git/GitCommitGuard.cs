namespace RetroIde.Application.Git;

/// <summary>Checks the commit Git intends to publish against the reviewed tree while the target ref is locked.</summary>
internal sealed class GitCommitGuard(string indexPath) : IDisposable
{
    private const string Script = """
        [ "$1" = prepared ] || exit 0
        {
            IFS= read -r reviewed_tree &&
            IFS= read -r reviewed_head &&
            IFS= read -r reviewed_ref
        } < "$GIT_INDEX_FILE.review" || exit 1
        active_ref=$(git symbolic-ref --quiet HEAD) || active_ref=HEAD
        while IFS=' ' read -r old_oid new_oid ref; do
            if [ "$ref" = "$active_ref" ] || [ "$ref" = HEAD ]; then
                tree=$(git rev-parse --verify "$new_oid^{tree}") || exit 1
                if [ "$active_ref" != "$reviewed_ref" ] ||
                   [ "$old_oid" != "$reviewed_head" ] ||
                   [ "$tree" != "$reviewed_tree" ]; then
                    printf '%s\n' 'Retro IDE: reviewed commit state changed' > "$GIT_INDEX_FILE.rejected"
                    exit 1
                fi
            fi
        done
        """;

    private string HookName { get; } = Path.GetFileName(indexPath);

    internal bool Rejected => File.Exists(indexPath + ".rejected");

    internal async Task<bool> PrepareAsync(GitWorktree repository, GitCommitOperations.CommitState review, CancellationToken token)
    {
        var hooks = NativeGit.WorktreeArguments(repository);
        Configure(hooks);
        hooks.AddRange(["hook", "list", "-z", "reference-transaction"]);
        var enabled = await NativeGit.RunAsync(repository.WorktreePath, hooks, token).ConfigureAwait(false);
        if (enabled?.Split('\0').Contains(HookName, StringComparer.Ordinal) != true)
            return false;

        var command = NativeGit.WorktreeArguments(repository);
        command.Add("write-tree");
        var tree = (await NativeGit.RunAsync(repository.WorktreePath, command, token, indexPath).ConfigureAwait(false))?.Trim();
        if (tree is null || tree.Length is not (40 or 64) || !tree.All(char.IsAsciiHexDigit))
            return false;

        var refName = string.Equals(review.Branch, "(detached)", StringComparison.Ordinal) ? "HEAD" : "refs/heads/" + review.Branch;
        var head = review.Head ?? new string('0', tree.Length);
        await File.WriteAllTextAsync(indexPath + ".review", $"{tree}\n{head}\n{refName}\n", token).ConfigureAwait(false);
        await File.WriteAllTextAsync(indexPath + ".guard", Script.ReplaceLineEndings("\n") + "\n", token).ConfigureAwait(false);
        return true;
    }

    internal void Configure(List<string> command)
    {
        // Git for Windows and Unix both use a POSIX shell for configured hook commands.
        // HookName is generated by the IDE and also limits inherited hooks to this prepared index.
        command.AddRange([
            "-c", $"hook.{HookName}.event=reference-transaction",
            "-c", $"hook.{HookName}.command=verify_review() {{ case \"$GIT_INDEX_FILE\" in *{HookName}) . \"$GIT_INDEX_FILE.guard\" ;; esac; }}; verify_review",
            "-c", $"hook.{HookName}.parallel=false",
        ]);
    }

    /// <inheritdoc />
    public void Dispose()
    {
        File.Delete(indexPath + ".guard");
        File.Delete(indexPath + ".review");
        File.Delete(indexPath + ".rejected");
    }
}
